'use strict';
/*
 * One connection pool, many databases.
 *
 * A shop's data lives in its own database. Serving several shops from one
 * process therefore means switching database per request - and the naive way to
 * do that is a separate mongoose.connect() per shop, which is a separate pool
 * per shop. That is what running a process per shop already does, and it is the
 * expensive part: twenty shops idling held 1,052 sockets open, because a pool is
 * per process and nothing was shared.
 *
 * connection.useDb() gives a Connection bound to a different database on the
 * *same* MongoClient. The pool, the monitoring, the topology - all shared. Ten
 * shops or a thousand cost one pool between them, and switching costs nothing on
 * the wire: the database name is a field in the message, not a new socket.
 *
 * Which makes the risky part not performance but correctness. Everything here
 * exists to make sure a request cannot be served from the wrong database:
 *
 *   - the name is validated before it reaches the driver, so a value that has
 *     been through a request header cannot name an arbitrary database;
 *   - admin, local and config are refused outright - they are not shops, and a
 *     bug that reached them would be reading server internals;
 *   - connections are cached by name, so a shop always gets the same object and
 *     two shops can never share one.
 *
 * Nothing in the single-shop path uses any of this. A till and a self-hosted
 * server have one database and go on using the default connection.
 */

const mongoose = require('mongoose');

/*
 * MongoDB itself rejects /\. "$*<>:|? and anything over 63 bytes, but that is
 * not the bar here. Tenant database names are generated by the control plane as
 * posnic_t_<subdomain>, so anything outside this alphabet did not come from
 * there, and the right response is to refuse rather than to sanitise and
 * continue with a name nobody intended.
 */
const VALID_NAME = /^[A-Za-z0-9_-]{1,63}$/;

/* Server-internal databases. Not shops, and reaching one means a bug upstream. */
const RESERVED = new Set(['admin', 'local', 'config']);

/**
 * @param {string} name
 * @returns {string} the same name, if it is usable
 * @throws  {Error}  otherwise - never a fallback
 */
function assertUsableName(name) {
  const text = String(name == null ? '' : name);
  if (!VALID_NAME.test(text)) {
    throw new Error(`"${text}" is not a usable database name`);
  }
  if (RESERVED.has(text.toLowerCase())) {
    throw new Error(`"${text}" is a server database, not a shop`);
  }
  return text;
}

/**
 * A Connection for one shop's database, sharing the process's single pool.
 *
 * @param {string} dbName
 * @param {import('mongoose').Connection} [base] the pooled connection to borrow
 * @returns {import('mongoose').Connection}
 */
function tenantConnection(dbName, base = mongoose.connection) {
  const name = assertUsableName(dbName);
  if (!base || !base.readyState) {
    throw new Error('the database connection is not ready');
  }
  /* useCache so the same shop yields the same Connection object across
     requests. Without it every request builds a new Connection - and with it a
     new set of models - which leaks memory steadily under load. */
  return base.useDb(name, { useCache: true });
}

/**
 * Is this database name one this process may serve?
 *
 * Separate from tenantConnection so a caller can decide how to answer - a
 * router wants 404, a background job wants to throw - without a try/catch
 * around control flow.
 */
function isServableName(name) {
  try {
    assertUsableName(name);
    return true;
  } catch (e) {
    return false;
  }
}

module.exports = { tenantConnection, isServableName, assertUsableName, VALID_NAME, RESERVED };
