/* Rebuild the bundled route index and documentation audit from current UI. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const links = require('../docs/page-help-links.json');
const english = require('../languages/_english.json');
const topics = {};
function label(node) {
  const text = node && node.textContent.replace(/\s+/g, ' ').trim();
  const translated = node && node.querySelector('lang[class], [data-t]');
  return { title: text || 'Posnic', titleKey: translated && (translated.getAttribute('data-t') || translated.className.split(' ').find(k => k.startsWith('lang_'))) || null };
}
function put(route, title, source) {
  topics[route] = { ...title, guide: links[route] || null, status: links[route] ? 'needs-review' : 'missing', source };
}
const sidebar = new JSDOM(fs.readFileSync(path.join(root, 'frontend/layouts/sidebar.html'), 'utf8'));
sidebar.window.document.querySelectorAll('a[href^="#/"]').forEach(a => put(a.getAttribute('href').slice(2), label(a), 'frontend/layouts/sidebar.html'));
sidebar.window.close();
const header = new JSDOM(fs.readFileSync(path.join(root, 'frontend/layouts/header.html'), 'utf8'));
header.window.document.querySelectorAll('a[href^="#/"]').forEach(a => {
  const route = a.getAttribute('href').slice(2);
  if (!topics[route]) put(route, label(a), 'frontend/layouts/header.html');
});
header.window.close();
for (const name of fs.readdirSync(path.join(root, 'frontend/modules')).filter(n => n.endsWith('.html'))) {
  const source = 'frontend/modules/' + name;
  const dom = new JSDOM(fs.readFileSync(path.join(root, source), 'utf8'));
  for (const page of dom.window.document.querySelectorAll('.page_loader[id]')) {
    let route = page.id.replace(/_new$/, '');
    if (page.id === 'sales_new') route = 'sales/new';
    if (page.id === 'items_new') route = 'items/new';
    if (page.id === 'branchedit_new') route = 'branches/new';
    if (page.id === 'lowstockitems') route = 'lowstock';
    if (!topics[route]) put(route, label(page.querySelector('.page-title') || page.querySelector('h4,h5')), source);
  }
  dom.window.close();
}
// Real record actions must not be confused with the module's list page.
for (const module of ['items', 'categories', 'customers', 'suppliers', 'sales', 'receivings', 'purchaseorders', 'users', 'branches', 'quotes', 'expenses']) {
  const base = topics[module];
  if (!base) continue;
  for (const action of ['new', ':id', ':id/edit', ':id/delete']) {
    const route = module + '/' + action;
    if (!topics[route]) put(route, base, base.source);
  }
}
for (const route of Object.keys(links)) if (!topics[route]) {
  const base = topics[route.split('/')[0]];
  put(route, base || { title: 'Posnic', titleKey: 'lang_posnic' }, base ? base.source : 'frontend/static/script/js/routes.js');
}
const singular = { items: 'Item', categories: 'Category', customers: 'Customer', suppliers: 'Supplier', sales: 'Sale', receivings: 'Purchase', purchaseorders: 'Purchase Order', users: 'Employee', branches: 'Branch', quotes: 'Quotation', expenses: 'Cash Book Entry' };
for (const [route, topic] of Object.entries(topics)) {
  const parts = route.split('/');
  if (!singular[parts[0]]) continue;
  const action = parts[parts.length - 1];
  const prefix = action === 'new' ? 'Add' : action === 'edit' ? 'Edit' : action === 'delete' ? 'Delete' : null;
  if (!prefix) continue;
  const title = prefix + ' ' + singular[parts[0]];
  const key = Object.keys(english).find(k => english[k].toLowerCase() === title.toLowerCase());
  topic.title = title;
  topic.titleKey = key || null;
}
topics['sales/new'].title = 'Add Sale';
topics['sales/new'].titleKey = 'lang_add_sale';
topics['settings/taxmodule'].title = 'Tax Settings';
topics['settings/taxmodule'].titleKey = 'lang_help_tax_settings';
const sorted = Object.fromEntries(Object.entries(topics).sort(([a], [b]) => a.localeCompare(b)));
const sourceCommit = cp.execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
const coverage = { schemaVersion: 1, sourceCommit, guideOrigin: 'https://www.posnic.com/guides/posnic-pos-complete-user-guide/',
  reviewPolicy: 'Existing published links are needs-review until their current-version steps and screenshots are verified. Missing routes remain explicit; no guide is guessed.', routes: sorted };
fs.writeFileSync(path.join(root, 'docs/page-help-coverage.json'), JSON.stringify(coverage, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'frontend/static/script/js/core/page-help-topics.js'), '/* Generated by scripts/audit-page-help.js; guide review status is explicit. */\nwindow.PosnicHelpTopics = ' + JSON.stringify(sorted, null, 2) + ';\n');
console.log(JSON.stringify({ routes: Object.keys(sorted).length, linkedForReview: Object.values(sorted).filter(t => t.guide).length, missing: Object.values(sorted).filter(t => !t.guide).length, sourceCommit }));
