const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const read=name=>JSON.parse(fs.readFileSync(path.join(root,'api/src/json',name+'.json'),'utf8'));
const currency=read('country_currency');
const source=fs.readFileSync(path.join(root,'src/install-wizard.html'),'utf8');
const match=source.match(/const countryTimezones = (\{[\s\S]*?\n        \});/);
if(!match)throw Error('Setup timezone reference not found');
const data={countries:read('countries').countries.map(c=>[c.id,c.sortname,c.value,currency[c.sortname]||'']),states:read('states').states.map(s=>[s.country_id,s.name]),currencies:[...new Set(read('currency').currency.map(c=>c.text).filter(Boolean))],timezones:vm.runInNewContext('('+match[1]+')')};
fs.writeFileSync(path.join(root,'src/setup-region-data.js'),'// Generated by scripts/generate-setup-regions.js from bundled reference data.\nwindow.PosnicSetupRegionData = '+JSON.stringify(data)+';\n');
